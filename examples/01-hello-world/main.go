// Package main is the entry point for the Go program.
// Every executable Go program must have a main package.
package main

// Import the fmt package which contains functions for formatted I/O operations
// fmt is part of Go's standard library
import "fmt"

// The main function is the entry point of the program
// When you run the program, it starts executing from here
func main() {
	// fmt.Println is a function that prints text to the console
	// and automatically adds a newline at the end
	fmt.Println("Hello, World!")
}
